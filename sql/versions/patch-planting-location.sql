-- ---------------------------------------------------------------------------
-- 农事记录补「作业地点」字段
--
-- 背景：原先只存 gps（"23.131234,113.264567"），列表与时间轴都没法给人看，
-- 农户自己回看也认不出是哪块地。作业地点现在由前端自动带出（农场档案地址
-- + 自动定位坐标），需要落一个可读的文本。
--
-- 说明：该字段不参与上链摘要（DigestHelper 保持原样），否则算法一改，
-- 所有历史记录的 data_hash 重算都会对不上，会被误判成"存证被篡改"。
-- ---------------------------------------------------------------------------

ALTER TABLE `biz_planting_record`
  ADD COLUMN `location` VARCHAR(255) DEFAULT NULL COMMENT '作业地点文本（农场档案地址 + 坐标）'
  AFTER `gps`;
